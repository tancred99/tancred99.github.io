import json, subprocess
subprocess.run(['python3','build_vocab.py'],cwd='src',check=True,capture_output=True)
subprocess.run(['python3','src/lessons_src.py'],check=True,capture_output=True)
les=json.load(open('lessons.json'))
d=json.load(open('exercises.json')); v=json.load(open('vocab.json'))
def safe(s): return s.replace('</','<\\/')
s=open('template.html').read()
s=s.replace('/*__DATA__*/',safe(json.dumps({'exercises':d,'vocab':v,'lessons':les},ensure_ascii=False)))
s=s.replace('/*__ENGINE__*/',safe(open('src/engine.js').read()))
s=s.replace('/*__APP__*/',safe(open('src/app.js').read()))
s=s.replace('/*__FBCONFIG__*/',safe(open('src/firebase-config.js').read()))
s=s.replace('/*__CLOUD__*/',safe(open('src/cloud.js').read()))
open('index.html','w').write(s)
print('ok',len(d),'exercises',len(v),'words',sum(len(x['exercises']) for x in les['lessons'].values()),'lesson items',len(s)//1024,'KB')
